/**
 * Updates a lead's status directly in Firestore using updateDoc.
 * Also synchronizes local state and records the timestamp.
 */
export async function updateCRMLeadStatus(
  leadId: string,
  newStatus: LeadStatus,
): Promise<{ success: boolean; error?: string }> {
  try {
    const updatedAt = new Date().toISOString();

    // If real Firestore user
    if (leadId && !leadId.startsWith("lead-")) {
      await updateDoc(doc(db, "users", leadId), {
        leadStatus: newStatus,
        lastContacted: updatedAt,
      });
    }

    // Also update custom leads if present
    const custom = getCustomLeads();
    const idx = custom.findIndex((c) => c.id === leadId);
    if (idx !== -1) {
      custom[idx] = {
        ...custom[idx],
        status: newStatus,
        lastContacted: updatedAt,
      };
      if (typeof window !== "undefined") {
        localStorage.setItem(STORAGE_KEYS.CUSTOM_LEADS, JSON.stringify(custom));
      }
    }

    return { success: true };
  } catch (err) {
    console.error("Failed to update lead status in Firestore:", err);
    return {
      success: false,
      error: err instanceof Error ? err.message : "Failed to update status in Firestore",
    };
  }
}

/**
 * Retrieves the current leads list and generates a downloadable CSV file.
 */
export function exportLeadsToCSV(
  leadsToExport: CRMLead[],
  filenamePrefix = "raffila-crm-leads",
): { count: number } {
  if (typeof window === "undefined" || !leadsToExport.length) {
    return { count: 0 };
  }

  const headers = [
    "Lead ID",
    "Full Name",
    "Phone / WhatsApp",
    "Email Address",
    "Location",
    "Status",
    "Tickets Purchased",
    "Total Spend (NGN)",
    "Last Contacted Date",
    "Assigned Representative",
  ];

  const escapeCSV = (val: unknown): string => {
    if (val === null || val === undefined) return '""';
    const str = String(val).replace(/"/g, '""');
    return `"${str}"`;
  };

  const rows = leadsToExport.map((lead) => [
    escapeCSV(lead.id),
    escapeCSV(lead.name),
    escapeCSV(lead.phone),
    escapeCSV(lead.email || ""),
    escapeCSV(lead.location),
    escapeCSV(lead.status.toUpperCase()),
    escapeCSV(lead.ticketsBought),
    escapeCSV(`₦${lead.totalSpent.toLocaleString()}`),
    escapeCSV(
      lead.lastContacted ? new Date(lead.lastContacted).toLocaleString("en-NG") : "Not contacted",
    ),
    escapeCSV(lead.assignedTo || "Unassigned"),
  ]);

  const csvContent = [headers.join(","), ...rows.map((r) => r.join(","))].join("\r\n");

  const blob = new Blob(["\uFEFF" + csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  const dateStr = new Date().toISOString().slice(0, 10);
  link.setAttribute("href", url);
  link.setAttribute("download", `${filenamePrefix}-${dateStr}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);

  return { count: leadsToExport.length };
}
