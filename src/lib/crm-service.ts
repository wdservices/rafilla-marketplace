export interface StaffMember {
  id: string;
  key: string; // e.g. RAF-SALES-9281-5410
  name: string;
  email: string;
  role: string;
  status: "active" | "revoked";
  createdAt: string;
  lastLoginAt?: string;
  callsCount?: number;
}

export type LeadStatus = "new" | "contacted" | "qualified" | "lost" | "hot" | "warm" | "converted";

export interface CRMLead {
  id: string;
  name: string;
  phone: string;
  email: string;
  location: string;
  status: LeadStatus;
  ticketsBought: number;
  totalSpent: number;
  lastContacted?: string;
  assignedTo?: string;
}

export type CallType =
  | "outbound_pitch"
  | "inbound"
  | "whatsapp"
  | "ticket_inquiry"
  | "winner_assistance"
  | "general_outreach";

export type CallOutcome = "converted" | "interested" | "follow_up" | "no_answer" | "not_interested";

export interface CRMCallLog {
  id: string;
  staffKey: string;
  staffName: string;
  leadId?: string;
  clientName: string;
  clientPhone: string;
  clientEmail?: string;
  callDuration?: string;
  durationMinutes?: number;
  callType: CallType;
  outcome: CallOutcome;
  notes: string;
  followUpDate?: string;
  createdAt: string;
}

export interface CRMActivity {
  id: string;
  activityType: "call";
  leadId: string;
  clientName: string;
  clientPhone: string;
  clientEmail?: string;
  callDuration: string;
  durationMinutes: number;
  outcome: CallOutcome;
  notes: string;
  callType: CallType;
  followUpDate?: string;
  staffKey: string;
  staffName: string;
  createdAt: string;
}

const STORAGE_KEYS = {
  STAFF: "raffila_crm_staff_v2",
  LOGS: "raffila_crm_call_logs_v2",
  CUSTOM_LEADS: "raffila_crm_custom_leads_v2",
  SESSION: "raffila_crm_staff_session",
};

/**
 * Returns real staff keys generated by Admin.
 * Starts empty: no dummy reps.
 */
export function getStaffList(): StaffMember[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.STAFF);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

/**
 * Admin generates a new real Sales Staff Key.
 */
export function generateStaffKey(name: string, email: string, role: string): StaffMember {
  const random4 = () => Math.floor(1000 + Math.random() * 9000);
  const key = `RAF-SALES-${random4()}-${random4()}`;
  const newStaff: StaffMember = {
    id: `staff-${Date.now()}`,
    key,
    name: name.trim(),
    email: email.trim().toLowerCase(),
    role: role.trim() || "Sales Representative",
    status: "active",
    createdAt: new Date().toISOString(),
    callsCount: 0,
  };

  const list = getStaffList();
  list.unshift(newStaff);
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(list));
  }
  return newStaff;
}

export function revokeStaffKey(key: string): boolean {
  const list = getStaffList();
  const staff = list.find((s) => s.key === key);
  if (!staff) return false;
  staff.status = "revoked";
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(list));
  }
  return true;
}

export function activateStaffKey(key: string): boolean {
  const list = getStaffList();
  const staff = list.find((s) => s.key === key);
  if (!staff) return false;
  staff.status = "active";
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(list));
  }
  return true;
}

export function deleteStaffKey(id: string): void {
  const list = getStaffList().filter((s) => s.id !== id);
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(list));
  }
}

export function validateStaffLogin(key: string): {
  success: boolean;
  staff?: StaffMember;
  error?: string;
} {
  const cleanKey = key.trim().toUpperCase();
  const list = getStaffList();
  const staff = list.find((s) => s.key === cleanKey);
  if (!staff) {
    return {
      success: false,
      error: "Invalid Sales Access Key. Ask your administrator for an active key.",
    };
  }
  if (staff.status === "revoked") {
    return {
      success: false,
      error: "This Sales Access Key has been revoked by the administrator.",
    };
  }
  staff.lastLoginAt = new Date().toISOString();
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(list));
    localStorage.setItem(STORAGE_KEYS.SESSION, JSON.stringify(staff));
  }
  return { success: true, staff };
}

export function getCurrentStaffSession(): StaffMember | null {
  if (typeof window === "undefined") return null;
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.SESSION);
    if (!raw) return null;
    const session: StaffMember = JSON.parse(raw);
    const list = getStaffList();
    const live = list.find((s) => s.key === session.key);
    if (!live || live.status === "revoked") {
      localStorage.removeItem(STORAGE_KEYS.SESSION);
      return null;
    }
    return live;
  } catch {
    return null;
  }
}

export function clearStaffSession(): void {
  if (typeof window !== "undefined") {
    localStorage.removeItem(STORAGE_KEYS.SESSION);
  }
}

/**
 * Fetches real registered users from Firestore and maps them into CRM Leads.
 */
export async function fetchRealCRMLeads(): Promise<CRMLead[]> {
  try {
    const snap = await getDocs(query(collection(db, "users"), limit(200)));
    const leads: CRMLead[] = [];
    snap.docs.forEach((d) => {
      const data = d.data() as Record<string, unknown>;
      const name =
        (data["displayName"] as string) ||
        [data["firstName"], data["lastName"]].filter(Boolean).join(" ") ||
        (data["handle"] as string) ||
        (data["email"] as string) ||
        "Registered Entrant";
      const phone =
        (data["phone"] as string) || (data["phoneNumber"] as string) || "No phone added";
      const email = (data["email"] as string) || "";
      const location =
        (data["location"] as string) ||
        (data["city"] as string) ||
        (data["state"] as string) ||
        "Nigeria";
      const tickets =
        Number(data["totalEntries"] ?? data["entriesCount"] ?? data["ticketsCount"] ?? 0) || 0;
      const spent =
        Number(
          data["totalSpent"] ??
            (data["spentKobo"] ? Math.round(Number(data["spentKobo"]) / 100) : 0),
        ) || 0;
      const status: CRMLead["status"] = tickets > 5 ? "hot" : tickets > 0 ? "converted" : "warm";

      leads.push({
        id: d.id,
        name,
        phone,
        email,
        location,
        status,
        ticketsBought: tickets,
        totalSpent: spent,
        lastContacted: (data["lastContacted"] as string) || undefined,
        assignedTo: (data["assignedTo"] as string) || undefined,
      });
    });

    // Also append any custom leads added locally
    const custom = getCustomLeads();
    return [...leads, ...custom];
  } catch (err) {
    console.error("Could not fetch real users for CRM:", err);
    return getCustomLeads();
  }
}

function getCustomLeads(): CRMLead[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.CUSTOM_LEADS);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

export function addCRMLead(lead: Omit<CRMLead, "id">): CRMLead {
  const newLead: CRMLead = {
    id: `lead-${Date.now()}`,
    ...lead,
  };
  const leads = getCustomLeads();
  leads.unshift(newLead);
  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.CUSTOM_LEADS, JSON.stringify(leads));
  }
  return newLead;
}

/**
 * Returns real call logs recorded by sales staff.
 * Starts empty: no dummy calls.
 */
export function getCRMCallLogs(): CRMCallLog[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.LOGS);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch {
    return [];
  }
}

export function addCRMCallLog(log: Omit<CRMCallLog, "id" | "createdAt">): CRMCallLog {
  const newLog: CRMCallLog = {
    id: `log-${Date.now()}`,
    createdAt: new Date().toISOString(),
    ...log,
  };
  const logs = getCRMCallLogs();
  logs.unshift(newLog);

  // Update staff count
  const staffList = getStaffList();
  const staff = staffList.find((s) => s.key === log.staffKey);
  if (staff) {
    staff.callsCount = (staff.callsCount || 0) + 1;
  }

  if (typeof window !== "undefined") {
    localStorage.setItem(STORAGE_KEYS.LOGS, JSON.stringify(logs));
    localStorage.setItem(STORAGE_KEYS.STAFF, JSON.stringify(staffList));
  }
  return newLog;
}

/**
 * Saves a new call record directly to the 'crm_activities' collection in Firestore.
 * Captures call duration, outcome, notes, and specific lead metadata.
 */
export async function saveCallToCRMActivities(activityData: {
  leadId?: string;
  clientName: string;
  clientPhone: string;
  clientEmail?: string;
  callDuration: string;
  durationMinutes: number;
  outcome: CallOutcome;
  notes: string;
  callType: CallType;
  followUpDate?: string;
  staffKey: string;
  staffName: string;
}): Promise<CRMActivity> {
  const createdAt = new Date().toISOString();
  const payload = {
    activityType: "call",
    leadId: activityData.leadId || `lead-${Date.now()}`,
    clientName: activityData.clientName,
    clientPhone: activityData.clientPhone,
    clientEmail: activityData.clientEmail || "",
    callDuration: activityData.callDuration,
    durationMinutes: activityData.durationMinutes,
    outcome: activityData.outcome,
    notes: activityData.notes,
    callType: activityData.callType,
    followUpDate: activityData.followUpDate || "",
    staffKey: activityData.staffKey,
    staffName: activityData.staffName,
    createdAt,
    timestamp: serverTimestamp(),
  };

  let id = `activity-${Date.now()}`;
  try {
    const docRef = await addDoc(collection(db, "crm_activities"), payload);
    id = docRef.id;
  } catch (err) {
    console.warn("Failed to write crm_activities to Firestore, fallback to local:", err);
  }

  // If lead is a registered user, record lastContacted and status in Firestore
  if (activityData.leadId && !activityData.leadId.startsWith("lead-")) {
    try {
      await updateDoc(doc(db, "users", activityData.leadId), {
        lastContacted: createdAt,
        leadStatus: activityData.outcome === "converted" ? "converted" : "contacted",
      });
    } catch {
      // ignore
    }
  }

  // Also sync locally
  addCRMCallLog({
    staffKey: activityData.staffKey,
    staffName: activityData.staffName,
    leadId: activityData.leadId,
    clientName: activityData.clientName,
    clientPhone: activityData.clientPhone,
    clientEmail: activityData.clientEmail,
    callDuration: activityData.callDuration,
    durationMinutes: activityData.durationMinutes,
    callType: activityData.callType,
    outcome: activityData.outcome,
    notes: activityData.notes,
    followUpDate: activityData.followUpDate,
  });

  return {
    id,
    activityType: "call",
    ...activityData,
    leadId: activityData.leadId || "",
    createdAt,
  };
}

/**
 * Real-time listener for 'crm_activities' collection in Firestore.
 */
export function subscribeCRMActivities(
  callback: (activities: CRMActivity[]) => void,
  onError?: (err: Error) => void,
): () => void {
  try {
    const q = query(collection(db, "crm_activities"), limit(100));
    const unsubscribe = onSnapshot(
      q,
      (snapshot) => {
        const firestoreList: CRMActivity[] = [];
        snapshot.docs.forEach((d) => {
          const data = d.data() as Record<string, unknown>;
          firestoreList.push({
            id: d.id,
            activityType: "call",
            leadId: (data["leadId"] as string) || "",
            clientName: (data["clientName"] as string) || "Unknown Lead",
            clientPhone: (data["clientPhone"] as string) || "",
            clientEmail: (data["clientEmail"] as string) || undefined,
            callDuration: (data["callDuration"] as string) || "2 mins",
            durationMinutes: Number(data["durationMinutes"] || 2),
            outcome: (data["outcome"] as CallOutcome) || "interested",
            notes: (data["notes"] as string) || "",
            callType: (data["callType"] as CallType) || "outbound_pitch",
            followUpDate: (data["followUpDate"] as string) || undefined,
            staffKey: (data["staffKey"] as string) || "",
            staffName: (data["staffName"] as string) || "Staff Rep",
            createdAt: (data["createdAt"] as string) || new Date().toISOString(),
          });
        });

        // Merge with local logs so any locally created logs are present immediately
        const localLogs = getCRMCallLogs();
        const mergedMap = new Map<string, CRMActivity>();
        firestoreList.forEach((a) => mergedMap.set(a.id, a));
        localLogs.forEach((l) => {
          if (!mergedMap.has(l.id)) {
            mergedMap.set(l.id, {
              id: l.id,
              activityType: "call",
              leadId: l.leadId || "",
              clientName: l.clientName,
              clientPhone: l.clientPhone,
              clientEmail: l.clientEmail,
              callDuration: l.callDuration || "3 mins",
              durationMinutes: l.durationMinutes || 3,
              outcome: l.outcome,
              notes: l.notes,
              callType: l.callType,
              followUpDate: l.followUpDate,
              staffKey: l.staffKey,
              staffName: l.staffName,
              createdAt: l.createdAt,
            });
          }
        });

        const sorted = Array.from(mergedMap.values()).sort(
          (a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
        );
        callback(sorted);
      },
      (err) => {
        console.warn("Firestore onSnapshot error on crm_activities:", err);
        if (onError) onError(err);
        const local = getCRMCallLogs().map((l) => ({
          id: l.id,
          activityType: "call" as const,
          leadId: l.leadId || "",
          clientName: l.clientName,
          clientPhone: l.clientPhone,
          clientEmail: l.clientEmail,
          callDuration: l.callDuration || "3 mins",
          durationMinutes: l.durationMinutes || 3,
          outcome: l.outcome,
          notes: l.notes,
          callType: l.callType,
          followUpDate: l.followUpDate,
          staffKey: l.staffKey,
          staffName: l.staffName,
          createdAt: l.createdAt,
        }));
        callback(local);
      },
    );
    return unsubscribe;
  } catch (err) {
    console.error("subscribeCRMActivities init error:", err);
    return () => {};
  }
}

